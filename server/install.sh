  grep -q '^AUREA_KVIZ_ALLOWED_ORIGINS=' "$ENV_FILE" || echo "AUREA_KVIZ_ALLOWED_ORIGINS=$ORIGINS" >> "$ENV_FILE"
else
  umask 077
  cat > "$ENV_FILE" <<ENVEOF
# AUREA · настройки приёмника заявок. Права 600, читает только root (через systemd).
